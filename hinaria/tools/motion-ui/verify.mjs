import {fileURLToPath} from 'node:url';
import { chromium } from 'playwright';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('.',import.meta.url)).replace(/[\\/]$/,'');
await mkdir(root+'/verification',{recursive:true});
const server=createServer(async(req,res)=>{
 const path=new URL(req.url,'http://localhost').pathname;
 if(!['/ZERO_MOTION_STUDIO.html','/verification/downloaded-laboratory.html'].includes(path)){res.writeHead(404);res.end();return}
 try{res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(await readFile(root+path))}catch(_){res.writeHead(500);res.end()}
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({executablePath:process.env.HINARIA_CHROMIUM||undefined,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:1440,height:1040},deviceScaleFactor:1,acceptDownloads:true});
const page=await context.newPage();
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.message));
await context.route(/^https?:/,route=>{if(new URL(route.request().url()).origin===origin)return route.continue();external.push(route.request().url());return route.abort()});
const url=origin+'/ZERO_MOTION_STUDIO.html';
const hash=buffer=>createHash('sha256').update(buffer).digest('hex');
const seek=async value=>page.locator('#timeline').evaluate((e,v)=>{e.value=String(v);e.dispatchEvent(new Event('input',{bubbles:true}))},value);
const results=[];
try{
 await page.goto(url);
 await page.locator('#play').click();
 assert.equal(await page.locator('.demo-item').count(),32);
 const demos=await page.locator('.demo-item').evaluateAll(nodes=>nodes.map(n=>({id:n.dataset.demo,title:n.querySelector('.demo-name').textContent})));
 for(const demo of demos){
  await page.locator('[data-demo="'+demo.id+'"]').click();
  let first,second;
  for(const v of [0,80,610,1000]){
   await seek(v);
   assert.equal(await page.locator('#error').isVisible(),false,demo.id+' render error');
   const invalid=await page.locator('#preview').evaluate(e=>Array.from(e.querySelectorAll('*')).some(n=>Array.from(n.attributes).some(a=>/NaN|Infinity|undefined/.test(a.value))));
   assert.equal(invalid,false,demo.id+' invalid geometry');
   if(v===80)first=hash(await page.locator('#stage').screenshot());
   if(v===610)second=hash(await page.locator('#stage').screenshot());
  }
  assert.notEqual(first,second,demo.id+' does not visibly animate');
  results.push({id:demo.id,title:demo.title,frames:[0,.08,.61,1],geometry:'valid',visualChange:true});
  console.log('PASS '+demo.id);
 }
 await page.getByRole('button',{name:'Cenários',exact:true}).click();
 assert.equal(await page.locator('.demo-item').count(),6);
 await page.locator('#search').fill('nevoa');
 assert.equal(await page.locator('.demo-item').count(),1);
 assert.equal(await page.locator('.demo-item').getAttribute('data-demo'),'fog');
 await page.locator('#search').fill('sem_resultado_123');
 assert.equal(await page.locator('.demo-item').count(),0);
 assert.equal(await page.locator('.empty').count(),1);
 await page.locator('#search').fill('');
 await page.getByRole('button',{name:'Todos',exact:true}).click();
 await page.locator('[data-demo="portal"]').click();
 await seek(400);
 const still=hash(await page.locator('#stage').screenshot());
 await page.waitForTimeout(180);
 assert.equal(hash(await page.locator('#stage').screenshot()),still,'pause must freeze scene');
 await page.locator('#theme').click();
 assert.equal(await page.locator('#stage').evaluate(e=>e.classList.contains('light')),true);
 await page.locator('#theme').click();
 await page.locator('#duration').evaluate(e=>{e.value='2';e.dispatchEvent(new Event('input',{bubbles:true}))});
 await page.locator('#speed').selectOption('2');
 await page.locator('#loop').uncheck();
 await seek(800);
 await page.locator('#play').click();
 await page.waitForFunction(()=>document.getElementById('play-label').textContent==='Reproduzir',{},{timeout:2500});
 assert.equal(await page.locator('#timeline').inputValue(),'1000','non-loop ends at final frame');
 await page.locator('#loop').check();
 await seek(920);
 await page.locator('#play').click();
 await page.waitForTimeout(250);
 assert.ok(Number(await page.locator('#timeline').inputValue())<920,'loop wraps');
 await page.locator('#play').click();
 await page.locator('#restart').click();
 assert.equal(await page.locator('#timeline').inputValue(),'0');
 await page.locator('#search').focus();
 await page.keyboard.type('a');
 const prior=await page.locator('#timeline').inputValue();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#timeline').inputValue(),prior,'editing input must not seek');
 await page.locator('#search').fill('');
 await page.locator('#search').blur();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#timeline').inputValue(),'50');
 await page.keyboard.press('Space');
 assert.equal(await page.locator('#play-label').textContent(),'Pausar');
 await page.keyboard.press('Space');
 assert.equal(await page.locator('#play-label').textContent(),'Reproduzir');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
 const exported=root+'/verification/downloaded-laboratory.html';
 await download.saveAs(exported);
 assert.ok((await readFile(exported,'utf8')).includes("const catalog="));
 const exportedPage=await context.newPage();exportedPage.on('pageerror',e=>errors.push(e.message));
 await exportedPage.goto(origin+'/verification/downloaded-laboratory.html');
 assert.equal(await exportedPage.locator('.demo-item').count(),32);
 await exportedPage.close();
 await page.locator('#duration').evaluate(e=>{e.value='4';e.dispatchEvent(new Event('input',{bubbles:true}))});
 await page.locator('#speed').selectOption('1');
 for(const id of ['portal','walk','wind','modal','fire','liquid']){
  await page.locator('[data-demo="'+id+'"]').click();await seek(450);
  await page.screenshot({path:root+'/verification/'+id+'-desktop.png',fullPage:true});
 }
 const reduced=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,reducedMotion:'reduce'});
 const mobile=await reduced.newPage();mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto(url+'#cards');
 assert.equal(await mobile.locator('#play-label').textContent(),'Reproduzir');
 assert.equal(await mobile.locator('#reduced-notice').isVisible(),true);
 assert.equal(await mobile.locator('#detail-title').textContent(),'Cartas em leque');
 const dims=await mobile.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(dims.scroll<=dims.width,'mobile horizontal overflow: '+JSON.stringify(dims));
 await mobile.locator('#timeline').evaluate(e=>{e.value='550';e.dispatchEvent(new Event('input',{bubbles:true}))});
 await mobile.screenshot({path:root+'/verification/mobile.png',fullPage:true});
 await reduced.close();
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 const report={status:'PASS',browser:await browser.version(),protocol:'HTTP local (navegação file:// bloqueada pela política do Chromium deste ambiente)',demos:results,checks:['32 animações em quatro posições de tempo','Geometria sem NaN, Infinity ou referências indefinidas','Mudança visual real entre dois quadros de cada cena','Pausa congela a cena','Busca sem acentos, filtros e estado vazio','Repetição, fim de ciclo, duração e velocidade','Atalhos sem interferir na edição de campos','Download e reabertura do HTML','Mobile 390×844 sem rolagem horizontal','Movimento reduzido inicia pausado','Zero erros JavaScript','Zero solicitações externas'],errors,externalRequests:external};
 await writeFile(root+'/verification/report.json',JSON.stringify(report,null,2)+'\n');
 console.log('PASS ALL: 32 demos, controls, mobile, download, offline.');
}finally{await browser.close();await new Promise(resolve=>server.close(resolve))}
