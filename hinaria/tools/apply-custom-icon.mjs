import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const file=process.argv[2];
if(!file)throw new Error('Uso: node tools/apply-custom-icon.mjs /caminho/ICONE_HINATA.png');
const b=readFileSync(file);
if(b.length<24||b.subarray(0,8).toString('hex')!=='89504e470d0a1a0a') throw new Error('O ícone precisa ser um arquivo PNG real.');
const w=b.readUInt32BE(16),h=b.readUInt32BE(20);
if(w!==h||w<192) throw new Error(`Imagem ${w}x${h}: envie PNG quadrado >=192x192. Ideal 512x512.`);
const manifest=join(root,'android/app/src/main/AndroidManifest.xml');
if(!existsSync(manifest)) throw new Error('Projeto Android não existe. Execute a instalação do Capacitor primeiro.');
const res=join(root,'android/app/src/main/res/drawable-nodpi');
mkdirSync(res,{recursive:true});
copyFileSync(file,join(res,'hinaria_icon_custom.png'));
let txt=readFileSync(manifest,'utf8');
if(!/android:icon="[^"]+"/.test(txt))throw new Error('android:icon não encontrado no AndroidManifest.xml');
txt=txt.replace(/android:icon="[^"]+"/,'android:icon="@drawable/hinaria_icon_custom"');
txt=txt.replace(/android:roundIcon="[^"]+"/,'android:roundIcon="@drawable/hinaria_icon_custom"');
writeFileSync(manifest,txt);
console.log('Ícone substituído usando o PNG fornecido; execute npm run android:debug.');
