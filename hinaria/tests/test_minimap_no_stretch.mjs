assert.match(hud,/mmw\.style\.width = mmOff \? '' : s \+ 'px'/);
assert.match(hud,/mmw\.style\.height = mmOff \? '' : s \+ 'px'/);
console.log('PASS minimapa: ancoragem superior e dimensoes fixas, com ocultacao preservada.');
