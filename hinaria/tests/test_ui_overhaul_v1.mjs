import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=x=>readFileSync(join(root,x),'utf8');
const html=read('index.html'),main=read('src/core/bootGame.js'),code=read('src/ui/hudOverhaulV1.js'),css=read('assets/ui/hud-overhaul-v1.css');
assert.match(html,/assets\/ui\/hud-overhaul-v1\.css/);
assert.match(main,/initHudOverhaulV1\(\)/);
for(const id of ['arsenal-btn','chr','qbtn','hinaria-lore-button','perf-open']) assert.match(code,new RegExp(`data-original="${id}"`));
for(const id of ['s0','s1','s2']) assert.ok(code.includes(`original('${id}')`));
for(const id of ['s3','s4']) assert.match(css,new RegExp(`#${id}\\b`));
assert.match(code,/original\(action\.dataset\.original\)/);
assert.match(code,/target\.click\(\)/);
assert.match(css,/#hot:not\(\.ui-extras-open\) #s3/);
assert.match(css,/#ui1-menu-backdrop\[hidden\]/);
assert.match(css,/#quest-quick-toggle/);
assert.match(css,/#mmw/);
// The existing combat, quest and lore handlers remain independent of the new HUD.
assert.match(read('src/player/controls.js'),/getElementById\('chr'\)\.onclick/);
assert.match(read('src/quest/questUI.js'),/b\.onclick = toggleJournal/);
assert.match(read('src/lore/loreSystem.js'),/b\.addEventListener\('click',toggle\)/);
assert.match(read('src/ui/performanceUI.js'),/getElementById\('perf-open'\)\.addEventListener\('click'/);
console.log('UI V1: links, controls, layout, and preserved handlers verified.');
