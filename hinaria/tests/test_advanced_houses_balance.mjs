import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const text=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const combat=text('src/combat/combat.js');
const fragment=combat.slice(combat.indexOf('export const ENEMY_KINDS'),combat.indexOf('/**\n * Spawn an enemy'));
const ctx={Math,Error};vm.createContext(ctx);
vm.runInContext(fragment.replaceAll('export const ','const ').replace('export function ','function ') + ';globalThis.api={ENEMY_KINDS,enemyStatsForZone,SPAWN_ZONES}',ctx);
const {ENEMY_KINDS,enemyStatsForZone,SPAWN_ZONES}=ctx.api;
const rat=enemyStatsForZone('rat', {level:1});
assert.equal(rat.hp,12);
assert.deepEqual([...rat.dmg],[1,2]);
const king=enemyStatsForZone('orc',{level:20,boss:true,bossId:'orc_king'});
const troll=enemyStatsForZone('troll',{level:14,boss:true});
// Still intimidating bosses, no longer one-shot/excessive sponge extremes.
assert.ok(king.hp>=900&&king.hp<=1600,`Orc King HP=${king.hp}`);
assert.ok(king.dmg[1]<=50,`Orc King max hit=${king.dmg[1]}`);
assert.ok(troll.hp>=300&&troll.hp<=600,`Troll HP=${troll.hp}`);
assert.ok(troll.dmg[1]<=25);
assert.ok(SPAWN_ZONES.length>=10);
const knight=text('src/player/player.js');
for(const id of ['kn','pa','so','dr'])assert.match(knight,new RegExp('\\b'+id+': \\{'));
const arsenal=text('src/player/arsenal.js');
for(const id of ['kn_sun','pa_moon','so_star','dr_nature'])assert.ok(arsenal.includes(`id:'${id}'`));
const room=text('src/world/houseInteriors.js');
assert.ok(room.includes('cloneHouseAvatar(gameState.P.mesh)'));
assert.ok(!room.includes('gameState.P.mesh.clone(true)'));
for(const name of ['smith quarter','south tavern','chapel','abandoned cabin'])assert.ok(room.includes(name));
assert.ok(room.includes('inspectHouseObject'));
assert.ok(text('src/player/controls.js').includes("if(k==='e'){"));
console.log('PASS Casas avançadas + balanceamento: clone sem JSON cíclico, inspeção E, áreas temáticas, ratos, bosses, classes e arsenal.');
