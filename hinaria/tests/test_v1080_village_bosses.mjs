import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createQuestSystem} from '../src/quest/questSystem.js';
import {QUESTS} from '../src/quest/questData.js';
import {PART2_LAYOUT,PART2_SPAWNS} from '../src/content/part2.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const world=read('src/world/world.js');
const part=world.slice(world.indexOf('// Seeded random for reproducible world'),world.indexOf('/**\n * Build Three.js meshes for the world')).replaceAll('export const ','const ').replaceAll('export function ','function ');
const state={G:[],ZN:[],B:[],OB:[],CLR:[],HO:[],CH:[],LM:[],BRG:[],HS:[]};
vm.runInNewContext(part+'\ngenerateWorld();',{CONFIG:{WORLD_SIZE:64},gameState:state,console,PART2_LAYOUT,PART2_SPAWNS});
const cabin=state.HO.find(h=>h.district==='abandoned cabin');
assert.ok(cabin,'Cabana Abandonada deve existir no fim do mapa');
assert.equal(cabin.x,28); assert.equal(cabin.z,58);
for (const z of [60,61]) {
 assert.equal(state.B[28][z],0,`Caminho da cabana livre z=${z}`);
 assert.equal(state.RC[28*64+z],1,`Caminho da cabana acessível z=${z}`);
}
const cabanaChest=state.CH.find(c=>c.n==='Baú da Cabana');
assert.ok(cabanaChest,'Baú da Cabana preservado');
assert.notEqual(cabanaChest.x,28,'Baú não deve bloquear o centro da porta');
const well=state.OB.find(o=>o.t==='well'&&o.district==='plaza');
assert.ok(well,'Poço na praça');
assert.ok(Math.hypot(well.x-8.5,well.z-11)>4,'Poço não fica colado na casa do oeste');
assert.equal(state.HO.length,8,'Todas as casas preservadas');
const doors=state.HO.map(h=>({h,ix:Math.round(h.x),iz:Math.round(h.z+h.d/2+1)}));
for(const {h,ix,iz} of doors){assert.equal(state.B[ix][iz],0,`Porta livre ${h.district}`);assert.equal(state.RC[ix*64+iz],1,`Porta acessível ${h.district}`);}
let level=1;
const discovered=new Set(['Mirante do Vale','Ponte Velha','Acampamento dos Trolls','Caverna Sombria']);
const rewards=[];
const q=createQuestSystem(QUESTS,{level:()=>level,discovered:n=>discovered.has(n),reward:r=>rewards.push(r)});
assert.equal(q.status('boss_troll'),'locked');
q.start('c1_ratos');for(let i=0;i<4;i++)q.emit('kill',{k:'rat'});q.talk('bram','hi');
assert.equal(q.status('c1_ratos'),'done');
q.start('c1_espelho');q.talk('yoki','hi');
assert.equal(q.status('c1_espelho'),'done');
assert.equal(q.status('boss_troll'),'locked','Missão só libera no nível recomendado de desbloqueio');
level=8;
assert.equal(q.status('boss_troll'),'available');
q.start('boss_troll');
q.emit('kill',{k:'troll',bossId:null});
assert.equal(q.status('boss_troll'),'active','Troll comum não conta como chefe');
q.emit('kill',{k:'troll',bossId:'troll_ancient'});
q.talk('yoki','hi');
assert.equal(q.status('boss_troll'),'done','Troll Ancião concluído');
assert.equal(q.status('boss_orc'),'locked','Rei dos Orcs bloqueado abaixo do nível');
level=14;
assert.equal(q.status('boss_orc'),'available');
q.start('boss_orc');
q.emit('kill',{k:'orc',bossId:'troll_ancient'});
assert.equal(q.status('boss_orc'),'active','Chefe errado não satisfaz missão');
q.emit('kill',{k:'orc',bossId:'orc_king'});q.talk('bram','hi');
assert.equal(q.status('boss_orc'),'done');
assert.equal(rewards.length,4,'recompensas das missões preservadas');
const loop=read('src/core/loop.js');
assert.ok(loop.includes('updateTags();'));
assert.doesNotMatch(loop,/tagClock\s*>=\s*0\.09/,'Nomes não podem ter atualização lenta');
const house=read('src/world/houseInteriors.js');
assert.match(house,/abandoned cabin/);
assert.match(read('src/ui/dialogueUI.js'),/if \(nearbyHouse\(\)\) return enterHouse\(\)/);
console.log('PASS 1.0.8.0: cabana remota acessível e baú preservado; 8 portas livres; poço realocado; boss quests/level/kill exato; etiquetas 60 FPS');
