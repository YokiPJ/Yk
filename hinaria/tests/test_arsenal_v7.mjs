import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { WEAPONS, weaponsForClass, ensureArsenal, buyOrEquip, buySkill, skillLevel, skillCost, equippedWeapon, saveArsenalProgress, loadArsenalProgress } from '../src/player/arsenal.js';
const repo = new URL('../',import.meta.url);
const text = path => readFileSync(new URL(path,repo),'utf8');
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
function fresh(cls='kn',gold=0){return ensureArsenal({cls,gold,bonus:0,ownedWeapons:[],equippedWeapons:{},skillLevels:{}});}
assert.equal(WEAPONS.length,21);
assert.equal(new Set(WEAPONS.map(w=>w.id)).size,21);
for(const cls of ['kn','pa','so','dr','yo']){
 const P=fresh(cls,0);
 const items=weaponsForClass(cls);
 assert.equal(items.length,cls==='yo'?1:5);
 assert.equal(equippedWeapon(P).id,items[0].id);
 assert.equal(P.gold,0);
 assert.equal(skillLevel(P,3),0);
 if(cls!=='yo') assert.equal(buyOrEquip(P,items[3].id).ok,false,'no free paid weapon');
 assert.equal(buySkill(P,3).ok,false,'no free special');
 P.gold=cls==='yo'?0:items[1].cost;
 const selected=cls==='yo'?items[0]:items[1];
 const result=buyOrEquip(P,selected.id);
 assert.ok(result.ok);
 assert.equal(P.gold,0);
 assert.equal(equippedWeapon(P).id,selected.id);
 assert.equal(P.bonus,selected.bonus);
 assert.ok(buyOrEquip(P,items[0].id).ok,'can change back to default');
 assert.ok(buyOrEquip(P,selected.id).ok,'can re-equip at no cost');
 assert.equal(P.gold,0);
 assert.equal(buyOrEquip(P,WEAPONS.find(w=>w.cls!==cls).id).ok,false);
 P.gold=160;
 assert.equal(skillCost(P,3),160);
 assert.ok(buySkill(P,3).ok);
 assert.equal(P.gold,0);
 assert.equal(skillLevel(P,3),1);
 P.gold=80;
 assert.ok(buySkill(P,3).ok);
 assert.equal(skillLevel(P,3),2);
 P.gold=170;
 assert.ok(buySkill(P,3).ok);
 assert.equal(skillLevel(P,3),3);
 assert.equal(skillCost(P,3),0);
 assert.equal(buySkill(P,3).ok,false);
 assert.equal(weaponsForClass(cls).length,cls==='yo'?1:5);
 assert.ok(saveArsenalProgress(P));
 const restored=fresh(cls);
 assert.ok(loadArsenalProgress(restored));
 ensureArsenal(restored);
 assert.equal(restored.gold,0);
 assert.equal(restored.equippedWeapons[cls],selected.id);
 assert.equal(skillLevel(restored,3),3);
}
const models=text('src/player/weaponModels.js');
for(const w of WEAPONS){ assert.match(models,new RegExp('\\b'+w.model+':'),'Missing model: '+w.model); }
const html=text('index.html');
for(const id of ['arsenal-modal','arsenal-btn','arsenal-items','arsenal-gold','s4'])assert.ok(html.includes('id="'+id+'"')||html.includes("id='"+id+"'"),id+' element missing');
assert.match(text('src/ui/arsenalUI.js'),/applyAppearance\(P\)/);
assert.match(text('src/core/loop.js'),/attackRange = weapon.range/);
assert.match(text('src/player/player.js'),/loadArsenalProgress\(P\)/);
assert.match(text('src/combat/combat.js'),/group.scale.setScalar\(1\.5\)/,'Rat silhouette upgrade missing');
assert.match(text('src/combat/combat.js'),/from===gameState.P && equippedWeapon\(from\).kind==='bow'/,'Arrows projectile missing');
assert.match(text('src/combat/combat.js'),/const skillLv=skillLevel/,'Skill unlocking not integrated');
assert.match(text('src/ui/dialogueUI.js'),/Aceitar missão/);
assert.match(text('src/ui/dialogueUI.js'),/Entregar missão/);
console.log('PASS HINÁRIA Arsenal: 21 weapons / 5 classes; buy, equip, skill unlock, persistence, visible rat and arrows, UI elements');
