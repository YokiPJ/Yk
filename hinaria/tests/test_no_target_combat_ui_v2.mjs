import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {findForwardEnemy} from '../src/combat/forwardHit.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read = f => readFileSync(join(root,f),'utf8');
const P={x:10,z:10,mesh:{rotation:{y:0}}};
const front={x:10,z:11,hp:12,kind:'m'};
const behind={x:10,z:9,hp:12,kind:'m'};
const side={x:12,z:10,hp:12,kind:'m'};
const st={ents:[behind,front,side],B:[]};
assert.equal(findForwardEnemy(st,P,2),front,'front enemy is preferred');
assert.equal(findForwardEnemy({...st,ents:[behind]},P,2),null,'no damage to enemy behind player');
assert.equal(findForwardEnemy({...st,ents:[side]},P,2),side,'side target within generous front 180-degree arc');
assert.equal(findForwardEnemy({...st,ents:[{...front,hp:0}]},P,2),null,'dead enemy ignored');
assert.equal(findForwardEnemy({...st,ents:[front]},P,.5),null,'range respected');
const B=[]; B[10]=[];B[10][11]=1;
assert.equal(findForwardEnemy({ents:[front],B},P,2),null,'walls block attacks');
P.mesh.rotation.y=Math.PI;
assert.equal(findForwardEnemy(st,P,2),behind,'turn around to hit previously-behind enemy');
const html=read('index.html');
const ctrl=read('src/player/controls.js');
const loop=read('src/core/loop.js');
const bridge=read('src/combat/combatV2Bridge.js');
const css=read('assets/ui/hud-overhaul-v1.css');
const hud=read('src/ui/hudOverhaulV1.js');
assert.doesNotMatch(html,/id=["']tg["']/);
assert.doesNotMatch(ctrl,/autoTarget|gameState\.tgt = E/);
assert.doesNotMatch(loop,/targetRing|Seleção de alvo por proximidade/);
assert.doesNotMatch(bridge,/gameState\.tgt/);
assert.match(hud,/dock\.append\(actions\)/);
assert.match(hud,/dock\.append\(hot\)/);
assert.match(css,/#ui-combat-dock/);
for (const id of ['combat-v2-attack','combat-v2-dodge','s0','s1','s2','s3','s4']) assert.match(html,new RegExp(`id=["']${id}["']`));
assert.match(bridge,/freeDodge\.active=true/,'universal dodge active');
assert.match(bridge,/freeDodge\.elapsed>=combatV2\.cfg\.dodgeIFrameStart/,'non-knight i-frames');
console.log('PASS UI V2: no lock-on, directional hits, walls, dock, universal dodge and controls.');
