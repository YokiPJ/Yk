import {strict as assert} from 'node:assert';
import {readFileSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const file=p=>readFileSync(join(root,p),'utf8');
const axe=file('src/player/replayAxeModel.js');
const world=file('src/vfx/worldAtmosphereV3.js');
const interiors=file('src/world/houseInteriors.js');
const loop=file('src/core/loop.js');
const main=file('src/core/bootGame.js');
const settings=file('src/ui/performanceUI.js');
const html=file('index.html');
assert.match(world,/new THREE\.Points\(geometry,material\)/,'ambient uses one Points draw call');
assert.match(world,/mobile\?14:26/,'particle count bounded on mobile');
assert.doesNotMatch(world,/requestAnimationFrame/,'atmosphere piggybacks existing game loop');
assert.match(axe,/new THREE\.Points\(sparkGeometry,sparkMaterial\)/,'axe uses one point cloud');
assert.match(axe,/sparks\.visible=awake/,'axe particles are hidden unless awakened');
assert.match(loop,/tickVisualAtmosphere\(gameState\.P, dt, gameState\.t\)/);
assert.match(main,/initializeVisualAtmosphere\(gameState\.scene\)/);
assert.match(interiors,/roomOwnedTextures/);
assert.match(interiors,/texture\.dispose\?\.\(\)/);
assert.match(settings,/atmosphereEnabled/);
assert.match(html,/id="perf-atmosphere-v3"/);
assert.doesNotMatch(world,/fetch\(|https?:\/\//,'no runtime external texture requests');
console.log('PASS Visual V3 integration, cost bounds and resource cleanup');
