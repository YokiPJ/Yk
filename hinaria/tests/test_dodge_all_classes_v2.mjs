import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const code=readFileSync(new URL('../src/combat/combatV2Bridge.js',import.meta.url),'utf8');
const start=code.indexOf('const freeDodge = ');
const end=code.indexOf('export function tickCombatV2(',start);
assert.ok(start>=0 && end>start);
const cut=code.slice(start,end).replaceAll('export function ','function ');
let calls=0;
const P={x:0,z:0,cls:'pa',hp:100,at:0,path:[],mesh:{rotation:{y:0}},b:{}};
const gs={P,ccOpen:false,arsenalOpen:false,dialogueOpen:false,insideHouse:false,cutsceneActive:false,keys:{},jx:0,jz:0,yaw:0};
const controller={cfg:{dodgeCost:28,dodgeCooldown:.95,dodgeSpeed:5.7,dodgeDuration:.4,dodgeIFrameStart:.075,dodgeIFrameEnd:.265,staminaRegen:17},requestDodge(){calls++;return true;}};
const sb={gameState:gs,combatV2:controller,attackAim:{clear(){}},syncCombatClass(){},active(){return false;},showFloatingText(){},say(){},Math};
vm.runInNewContext(cut+'\nthis.test={requestCombatV2Dodge,getDodgeMotion,tickFreeDodge,abortCombatDodgeOnCollision,freeDodge};',sb);
const {test}=sb;
assert.equal(test.requestCombatV2Dodge(),true,'Paladin can dodge');
assert.equal(test.freeDodge.active,true);
assert.equal(test.freeDodge.stamina,72);
assert.equal(test.requestCombatV2Dodge(),false,'Cannot spam dodge');
test.tickFreeDodge(.15,P);
assert.equal(P.combatV2Dodge,true);
assert.equal(test.getDodgeMotion().speed,5.7);
test.tickFreeDodge(.27,P);
assert.equal(P.combatV2Dodge,false);
assert.equal(test.requestCombatV2Dodge(),false,'Cooldown persists after dodge finishes');
test.tickFreeDodge(.54,P);
assert.equal(test.requestCombatV2Dodge(),true,'Dodge works again after cooldown');
test.abortCombatDodgeOnCollision();
assert.equal(test.freeDodge.active,false,'Collision stops dodge');
assert.equal(calls,0,'Generic dodge does not accidentally invoke Knight controller');
console.log('PASS manual dodge all classes: stamina, input, cooldown, animation, collision.');
